import type { Tier } from './tuning';

export type TailShape = 'forked' | 'lunate' | 'round' | 'truncate' | 'shark';
export type Pattern =
  | 'none'
  | 'hero'
  | 'gulp'
  | 'lateral'
  | 'neon'
  | 'spots'
  | 'mottled'
  | 'bars'
  | 'eyeBand'
  | 'tang'
  | 'parrot'
  | 'sheephead'
  | 'tigerBands'
  | 'photophores';
export type Behavior = 'school' | 'solo' | 'predator';
export type Special = 'sharkGills' | 'underbite' | 'lure' | 'spines' | 'fangs' | 'barbel' | 'hammer';

/** Fin extents are measured from the nose: t = 0 at the snout, t = 1 at the tail base. */
export interface FinDef {
  start: number;
  end: number;
  /** Height relative to body height. */
  height: number;
  /** How far the fin tip sweeps back, relative to the fin base length. */
  sweep?: number;
  spiky?: boolean;
}

export interface SpeciesDef {
  id: SpeciesId;
  name: string;
  tier: Tier;
  /** Nose to tail tip in world units. */
  length: number;
  body: {
    /** Max body height relative to length. */
    height: number;
    /** Half-width relative to half-height (lateral compression). */
    width: number;
    /** Position of the max height, measured from the nose. */
    hump: number;
    /** Tail-base thickness relative to body height. */
    peduncle: number;
    /** 0.4 = pointed snout, 1.3 = very blunt head. */
    bluntness: number;
    /** Vertical offset of the snout relative to body height. */
    snout: number;
    /** Lower profile scale relative to the upper profile. */
    belly: number;
  };
  tail: { shape: TailShape; size: number; spread: number };
  dorsal?: FinDef;
  dorsal2?: FinDef;
  anal?: FinDef;
  pectoral: { size: number; t?: number };
  pelvic?: { size: number };
  eye: { size: number; t: number; y: number; iris: string };
  colors: {
    back: string;
    mid: string;
    belly: string;
    fin: string;
    finEdge?: string;
    accent: string;
    accent2?: string;
  };
  pattern: Pattern;
  patternCount?: number;
  material: {
    roughness: number;
    clearcoat: number;
    iridescence?: number;
    metalness?: number;
    glow?: string;
    glowIntensity?: number;
  };
  swim: { freq: number; amp: number; wave: number };
  speed: { cruise: number; burst: number };
  behavior: Behavior;
  /** Preferred depth band as fraction of world height (0 = seabed, 1 = surface). */
  depth: [number, number];
  detectMul?: number;
  /** Mouth radius relative to length. */
  mouth?: number;
  special?: Special[];
  /** A player-controlled hero fish (bigger texture, cartoon eyes, wider jaw). */
  playable?: boolean;
}

export function isHero(def: SpeciesDef): boolean {
  return def.playable === true;
}

